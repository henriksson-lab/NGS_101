def pool_scene(kind):
    """Independent oligo inventory rows, never an annealed molecular complex."""
    sc = Scene()
    if kind == 'partread1':
        sc.strand('PartRead1', [Segment('PartRead1', PARTREAD1)])
    elif kind == 'inner':
        for name, seq in INNER.items():
            sc.strand(name, [Segment('source Read2 handle', illumina.TRUSEQ_READ2),
                             Segment(name + ' target region', seq[len(illumina.TRUSEQ_READ2):])])
    elif kind == 'outer':
        for name, seq in OUTER_SOURCE.items():
            sc.strand(name, [Segment(name, seq.upper())])
    elif kind in ('ig', 'tr'):
        selected = 'Ig' if kind == 'ig' else 'TCR'
        for i, (pool, seq) in enumerate(CAPTURE_SOURCE, 1):
            if pool == selected:
                # Preserve actual source rows, including repeats; this does not
                # impose the experiment's separate order-multiplicity or molarity.
                sc.strand('Data S1 probe row ' + str(i), [Segment(pool + ' probe', seq)])
    elif kind == 'blockers':
        for name, seq in BLOCKER_SOURCE.items():
            # N/V here are the published blocking-reagent pattern, not a sample
            # identifier or an invented concrete barcode/UMI value.
            if name == 'Read1+polyT':
                sc.strand(name, [Segment('source PartRead1 blocker portion', PARTREAD1),
                                 Segment('source N28 degenerate blocker window', 'N'*28, placeholder=True),
                                 Segment('source polyT30', 'T'*30),
                                 Segment('source degenerate VN end', 'VN', placeholder=True)])
            else:
                sc.strand(name, [Segment(name, seq)])
    else:
        raise ValueError('Unknown local source pool: ' + kind)
    return sc
